# Type Conversion in Python
a = 2
b = 4.25
sum = a + b   #2.0 + 4.25 = 6.25
print("The sum of a and b is:", sum)  # Output: 6.25


# Type conversion (casting)
c = "2"
d = 4.25
e = int(c) + d  # 2 + 4.25 = 6.25
print(type(c))
print("The sum of c and d is:", e)  # Output: 6.25

f = 3.14
f = str(f)  # Convert float to string
print(type(f))
print("The value of f is:", f)  # Output: "3.14"

