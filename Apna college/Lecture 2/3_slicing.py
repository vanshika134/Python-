str = "apna college"
print(str[1:4])  #ending index is not included
print(str[5:12]) #starting index is included, ending index is not included
print(str[0:5])  #starting index is included, ending index is not included
print(str[:5])   #starting index is 0, ending index is not included
print(str[5:])   #starting index is included, ending index is length of string
print(str[:])    #starting index is 0, ending index is length of string


