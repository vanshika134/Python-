# USING FOR AND RAMGE()
# Print numbers from 1 to 100
for i in range(1, 101):
    print(i)

print("----End of loop----")

# Print numbers from 100 to 1
for i in range(100, 0 , -1):
    print(i)

print("----End of loop----")

# Print the multiplication table of a number n.
n = int(input("Enter your number"))
for i in range(1,11):
    print(n*i)

print("----End of loop----")
