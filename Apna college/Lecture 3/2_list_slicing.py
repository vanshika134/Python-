marks = [94.4, 87.5, 95.2, 66.4, 45.1]

print(marks[1:4])    # Slicing from index 1 to 3 (4 is exclusive)
print(marks[:3])     # Slicing from the beginning to index 2 (3 is exclusive)
print(marks[2:])     # Slicing from index 2 to the end of the list
print(marks[:])      # Slicing the entire list
print(marks[-3:-1])  # Slicing from index -3 to -2 (last two elements)


